"""Count each implemented circuit stage and write its insertable LaTeX table."""

from pathlib import Path

import numpy as np

from covariance_benchmarks import (
    METHODS, READOUT_KINDS, amplitude_readout_circuit, covariance_preparation_circuit,
    hadamard_readout_circuit, pairwise_readout_circuit, qae_phase_states,
    readout_settings, single_pair_step_circuit, swap_readout_circuit,
)
from qclt_proposal_comparison import B_SHOTS
from quantum_walk_study import D, K, X0, MODES, make_walk

ROOT = Path(__file__).parent


def generate():
    spacing = np.full(D, .08 / 256)
    history = np.cumsum(np.ones((K, D)) @ np.rint(MODES / spacing), axis=0)
    walk, _ = make_walk(8, X0, np.eye(D), spacing, 14, track_displacement=False)
    phase_states = qae_phase_states(B_SHOTS // readout_settings("qae", D))
    phase_bits = phase_states.bit_length() - 1
    circuits = {
        "swap": swap_readout_circuit(history)[0],
        "hadamard": hadamard_readout_circuit(history)[0],
        "qae": amplitude_readout_circuit(history, 0, 1, phase_bits)[0],
        "qpca": covariance_preparation_circuit(history)[0],
        "pairwise": pairwise_readout_circuit(history, 0, 1)[0],
    }
    widths = {key: circuit.num_qubits for key, circuit in circuits.items()}
    widths.update(qclt_amr=walk.num_qubits, qclt_fixed=walk.num_qubits,
                  single_pair=single_pair_step_circuit(history)[0].num_qubits,
                  cs_upper=0, cs_average=0)
    lines = [
        r"% Generated by paper_costs.py; requires booktabs.",
        r"\begin{tabular}{@{}p{0.35\textwidth}rrp{0.19\textwidth}r@{}}",
        r"\toprule",
        r"Method & Stage qubits & Settings & Output & Step time \\",
        r"\midrule",
    ]
    for key, (label, _) in METHODS.items():
        if key in READOUT_KINDS:
            settings, output = readout_settings(key, D), r"Entries$^*$"
        elif key.startswith("cs_"):
            settings, output = 0, r"Classical bound$^*$"
        else:
            settings, output = 1, "Step"
        lines.append(f"{label} & {widths[key]} & {settings} & {output} & -- " + r"\\")
    qae_calls = readout_settings("qae", D) * (2 * (phase_states - 1) + 1)
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\smallskip",
        r"\footnotesize Counts use the same $d=2$, $K=3$ history and two 8-bit step coordinates. "
        r"QCLT widths include the complete walk; single-pair width includes a compiled step with history supplied classically. "
        r"Other quantum widths count the covariance stage only. "
        r"$^*$These outputs require a Gaussian loader: at least 16 step-register qubits, plus implementation-dependent workspace. "
        r"Readout-stage and step registers may be reused between circuits. "
        r"Cauchy--Schwarz rows are classical arithmetic with exact variances supplied; zero counts only that stage. "
        r"The covariance-preparation replica has one coordinate qubit and two history-index qubits; its two settings read real matrix entries. "
        r"Amplitude estimation uses " + str(phase_bits) +
        r" phase qubits and " + str(qae_calls) +
        r" total calls to $A$ or $A^{-1}$ within the " + str(B_SHOTS) + r"-call budget. "
        r"Classical loader construction, coherent data-access oracles, AMR history measurements, and hardware execution times are not included in these stage widths. "
        r"Dashes indicate that hardware step latency has not been measured.\par",
    ])
    output = ROOT / "paper" / "figures" / "method_costs.tex"
    output.write_text("\n".join(lines) + "\n")
    print(f"Saved {len(METHODS)} method resource rows to {output}")


if __name__ == "__main__":
    generate()
