"""Generate LaTeX resource tables from the circuits used in the comparisons."""

import itertools
import statistics
import time
from pathlib import Path

import numpy as np

import cov_methods as C
import tdrjmcmc_qclt as T
from quantum_walk_study import D, K, X0, make_walk

ROOT = Path(__file__).parent
OUT = ROOT / "figures" / "quantum_walk"


def cpu_step_times(reps=8_000):
    """Microseconds for classical samplers on this host; covariance setup excluded."""
    rng = np.random.default_rng(31015)
    d, k = 5, 24
    H = rng.normal(size=(k, d))
    cov = np.cov(H.T)
    L = np.linalg.cholesky(cov)
    pairs = np.array(list(itertools.combinations(range(k), 2)))
    differences = H[pairs[:, 0]] - H[pairs[:, 1]]
    alpha = 2.38 / np.sqrt(d * (k * (k - 1)))

    def bench(fn):
        vals = []
        for _ in range(3):
            t0 = time.perf_counter()
            for _ in range(reps):
                fn()
            vals.append((time.perf_counter() - t0) * 1e6 / reps)
        return statistics.median(vals)

    return {
        "AM Gaussian draw": bench(lambda: L @ rng.normal(size=d)),
        "DE-MCz pair difference": bench(lambda: 2.38 / np.sqrt(2 * d) *
                                         (H[(ij := pairs[rng.integers(len(pairs))])[0]] - H[ij[1]])),
        "QCLT law (classical equivalent)": bench(lambda: alpha * (rng.choice((-1, 1), len(pairs)) @ differences)),
        "Zero-mean Gaussian draw": bench(lambda: L @ rng.normal(size=d)),
    }


def latex_escape(s):
    return (str(s).replace("\\", r"\textbackslash{}").replace("&", r"\&")
            .replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")
            .replace("—", "--"))


def generate():
    OUT.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(C.SEED)
    data = C.random_dataset(rng)
    covariance = C.qubit_counts(data)
    cpu = cpu_step_times()
    resource_rows = []
    details = {
        "Max (CS)": ("Covariance estimate; five coordinate variance bounds."),
        "Min (CS)": ("Covariance estimate; same width as maximum bound."),
        "Zero-mean": ("Uncentred second moment; one circuit per entry."),
        "Pairwise": ("Centered entries; proposal loader required."),
        "SWAP test": ("Cross terms; centered-column norms supplied."),
        "CLT quantum": ("Direct next-step kick; N=8 history values."),
        "CLT classical": ("Classical sampler; no circuit."),
    }
    for label, qubits, circuits in covariance:
        if label in details:
            note = details[label]
        elif label.startswith("QCLT-AP"):
            note = "D=5, K=6; 16-bit parameter and quantum history registers."
        elif label.startswith("QCLT + AMR"):
            note = "D=5, K=6; 6-bit AMR and quantum history registers."
        else:
            note = "Counted from the constructed circuit."
        resource_rows.append((label.replace("\n", " "), str(qubits), str(circuits), "--", note))
    pairwise_qubits = next(int(q) for label, q, _ in covariance if label == "Pairwise")
    qae_phase_bits = int(np.floor(np.log2(C.BUDGET_B // (C.D * (C.D + 1) // 2))))
    resource_rows.extend([
        ("Pairwise QAE readout", str(pairwise_qubits + qae_phase_bits),
         str(C.D * (C.D + 1) // 2), "--", f"Canonical QAE; {qae_phase_bits} phase bits; loader required."),
        ("Diagonal covariance approximation", "0", "0", "--", "Classical approximation; no circuit."),
        ("Isotropic covariance approximation", "0", "0", "--", "Classical approximation; no circuit."),
        ("QCLT window-only kick", str(C.D * 8 + C.D * ((8).bit_length() + 1)), "1", "--",
         "D=5, eight sign coins per axis; pilot covariance supplied."),
        ("QCLT coherent walk demo", "33", "1", "--", "D=2, K=3, 8-bit positions; known modes."),
        ("Adaptive Metropolis", "0", "0", f"{cpu['AM Gaussian draw']:.2f}",
         "Classical Gaussian draw; covariance setup excluded."),
        ("DE-MCz", "0", "0", f"{cpu['DE-MCz pair difference']:.2f}",
         "Classical pair difference; K=24."),
        ("QCLT law, classical equivalent", "0", "0", f"{cpu['QCLT law (classical equivalent)']:.2f}",
         "Same law as full QCLT kick; K=24."),
        ("Zero-mean Gaussian step", "0", "0", f"{cpu['Zero-mean Gaussian draw']:.2f}",
         "Classical draw; covariance precomputed."),
    ])
    header = r"""% Generated by paper_costs.py; requires booktabs.
\footnotesize
\setlength{\tabcolsep}{2pt}
\begin{tabular}{@{}p{2.7cm}rrrp{4.6cm}@{}}
\toprule
Method & Qubits & Circuits$^*$ & Step ($\mu$s) & Resource note \\
\midrule
"""
    body = "\n".join(" & ".join(latex_escape(v) for v in row) + r" \\" for row in resource_rows)
    footer = r"""
\bottomrule
\end{tabular}
\par\smallskip
\footnotesize Circuit widths are logical counts from the constructed circuits (covariance case: $d=5$, $N=8$); the QCLT sampler rows use $D=5$, $K=6$. $^*$Circuits per covariance estimate for estimators, or per step for samplers. CPU timings are per-proposal Python/NumPy timings on the current host; they are not quantum-hardware latency. Dashes mean no comparable CPU step timing was measured for that circuit. Readout methods output covariance entries and require a separate proposal loader.\par
"""
    path = OUT / "method_costs.tex"
    path.write_text(header + body + footer)
    print("saved", path)
    for name, value in cpu.items():
        print(f"{name}: {value:.2f} us/step (classical simulator)")


if __name__ == "__main__":
    generate()
