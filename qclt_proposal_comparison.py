"""Compare the ten next-step methods on the same 64 quantum histories.

Read in order: experiment, error table, saved data, comparison plot.
The circuit builders and finite-shot laws are in covariance_benchmarks.py.
"""
import itertools
import math
import sys
from pathlib import Path

import numpy as np

from covariance_benchmarks import (
    METHODS, project_psd, readout_estimate,
)

from quantum_walk_study import D, K, SCALE2, ISO_VAR, X0, MODES, history_branches
from quantum_walk_study import sample_walk
from amr_battle_test import window_from_history

ROOT = Path(__file__).parent
OUT = ROOT / "figures" / "quovar"
DATA = ROOT / "data" / "quantum_walk"
B_SHOTS = 384                  # Total readout shots or A/A-inverse calls


def frame_history(signs, center, axes, spacing):
    """Round each mode before accumulating positions, matching the circuit."""
    init = np.rint((X0 - center) @ axes / spacing)
    lmodes = np.rint(MODES @ axes / spacing)
    return init + np.cumsum(signs @ lmodes, axis=0)


def compare_methods(rng, n_windows=40, history_samples=1000):
    """Score every method against the same physical history covariance.

    The fixed grid rounds the two preparatory displacement modes. AMR changes
    the axes and spacing, while retaining the same two 8-bit registers.
    """
    local_spacing = np.full(D, .08 / 256)
    pilot = sample_walk(6, X0, np.eye(D), np.full(D, .08 / 64), 8, 20_000, 11)["physical_hist"]
    windows = [window_from_history(pilot[rng.choice(len(pilot), history_samples, replace=False)])
               for _ in range(n_windows)]
    extra_rng = np.random.default_rng(20261122)
    errors = {key: [] for key in METHODS}
    regularizer = ISO_VAR * np.eye(D)
    pairs = np.array(list(itertools.combinations(range(K), 2)))

    for signs, displacement in history_branches():
        target = SCALE2 * np.cov((X0 + displacement).T)
        normalizer = np.linalg.norm(target)
        history = frame_history(signs, X0, np.eye(D), local_spacing)
        covariance = np.cov(history.T)
        pair_steps = np.rint((2.38 / math.sqrt(2 * D))
                             * (history[pairs[:, 0]] - history[pairs[:, 1]]))
        # The bound midpoint retains variances and sets cross terms to zero.
        upper = np.outer(np.sqrt(np.diag(covariance)), np.sqrt(np.diag(covariance)))
        np.fill_diagonal(upper, np.diag(covariance))
        local_methods = {
            "qclt_fixed": SCALE2 * covariance + regularizer,
            "single_pair": pair_steps.T @ pair_steps / len(pairs) + regularizer,
            "cs_upper": SCALE2 * upper + regularizer,
            "cs_average": SCALE2 * np.diag(np.diag(covariance)) + regularizer,
        }
        basis = np.diag(local_spacing)
        for key, lattice_covariance in local_methods.items():
            physical_covariance = basis @ lattice_covariance @ basis.T
            errors[key].append(np.linalg.norm(physical_covariance - target) / normalizer)

        for center, axes, spacing in windows:
            rounded = frame_history(signs, center, axes, spacing)
            basis = axes @ np.diag(spacing)
            physical_covariance = basis @ (SCALE2 * np.cov(rounded.T) + regularizer) @ basis.T
            errors["qclt_amr"].append(np.linalg.norm(physical_covariance - target) / normalizer)

        basis = np.diag(local_spacing)
        # Existing methods retain their original random stream and draw order.
        for kind in ("pairwise", "swap", "qae", "hadamard", "qpca"):
            stream = extra_rng if kind in ("hadamard", "qpca") else rng
            estimates = project_psd(readout_estimate(history, kind, B_SHOTS, stream, 50))
            for estimate in estimates:
                physical_covariance = basis @ (SCALE2 * estimate + regularizer) @ basis.T
                errors[kind].append(np.linalg.norm(physical_covariance - target) / normalizer)
    return {key: np.asarray(errors[key]) for key in METHODS}


def write_covariance_table(errs, b_shots=B_SHOTS):
    """Write the requested ten methods, using the actual number of errors."""
    lines = [
        r"% Generated by qclt_proposal_comparison.py; requires booktabs.",
        r"\begin{tabular}{@{}p{0.48\textwidth}rrr@{}}",
        r"\toprule",
        r"Method & $N$ & Mean error (\%) & SD (\%) \\",
        r"\midrule",
    ]
    for key, (label, _) in METHODS.items():
        values = 100 * np.asarray(errs[key])
        lines.append(f"{label} & {len(values):,} & {values.mean():.2f} & "
                     f"{values.std(ddof=1):.2f} " + r"\\")
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\smallskip",
        r"\footnotesize All final step covariances are scored against the same continuous-history target. "
        r"Readout methods use a budget of " + str(b_shots) +
        r" shots, or calls to $A$ and $A^{-1}$ for amplitude estimation, and the same ideal Gaussian loader. "
        r"Covariance preparation includes finite-shot state readout added for this comparison. "
        r"SWAP and Hadamard receive exact column norms; covariance preparation receives the exact trace. "
        r"Both Cauchy--Schwarz approximations receive exact variances. "
        r"Averaging the upper and lower bounds gives diagonal covariance. "
        r"SD is one sample standard deviation, not an uncertainty on the mean.\par",
    ])
    path = ROOT / "paper" / "figures" / "covariance_method_errors.tex"
    path.write_text("\n".join(lines) + "\n")


def save_covariance_errors(errs, b_shots=B_SHOTS):
    DATA.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(DATA / "covariance_errors.npz", b_shots=b_shots, **errs)


def load_covariance_errors():
    with np.load(DATA / "covariance_errors.npz") as saved:
        return {key: saved[key] for key in METHODS}, int(saved["b_shots"])


def plot():
    """Plot mean covariance errors with one sample standard deviation (ddof=1).

    Compute both statistics from individual errors rather than rounded table
    entries.
    """
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib import pyplot as plt
    from matplotlib.lines import Line2D
    import paper_style

    errs, b_shots = load_covariance_errors()
    write_covariance_table(errs, b_shots)
    reference = float(np.mean(errs["qclt_amr"]))
    if not np.isfinite(reference) or reference <= 0:
        raise RuntimeError("QCLT + AMR covariance reference is invalid")
    paper_style.apply(font_scale=1.1)
    fig, ax = plt.subplots(figsize=(8.0, 6.0))
    visible_left = .1
    positions = []
    largest_interval = 0.
    for y, (key, (label, family)) in enumerate(METHODS.items()):
        values = errs[key] / reference
        mean, sd = float(values.mean()), float(values.std(ddof=1))
        largest_interval = max(largest_interval, mean + sd)
        color = paper_style.COLORS[family]
        ax.barh(y, mean, height=.78, color=color, alpha=paper_style.BAR_ALPHA,
                edgecolor=color, linewidth=.8, zorder=2)
        ax.errorbar(mean, y + .29, xerr=sd, fmt="o", markersize=3.,
                    markerfacecolor="white", markeredgecolor=paper_style.INK,
                    markeredgewidth=.8, ecolor=paper_style.INK,
                    elinewidth=.9, capsize=2.5, zorder=4)
        label = label.replace("Single history-pair difference", "Single history-pair\ndifference")
        label = label.replace("Covariance matrix preparation + readout", "Covariance matrix preparation\n+ readout")
        label = label.replace("Cauchy--Schwarz upper/lower average", "Cauchy--Schwarz\nupper/lower average")
        ax.text(math.sqrt(visible_left * mean), y, label, ha="center", va="center",
                color=paper_style.INK, zorder=5)
        positions.append(y)
    y = len(METHODS)
    ax.set_yticks(positions, [""] * len(positions))
    ax.tick_params(axis="y", length=0)
    ax.tick_params(axis="x", direction="out", length=3, color=paper_style.INK)
    ax.set_ylim(y - .5, -.5)
    ax.set_xscale("log")
    ax.set_xlim(visible_left, max(10., 5 * np.ceil(1.15 * largest_interval / 5)))
    ax.set_xlabel("Covariance error / QCLT + AMR (1 = QCLT + AMR)")
    paper_style.legend_below(ax, handles=[
        Line2D([0], [0], color=paper_style.INK, marker="o",
               markerfacecolor="white", markeredgecolor=paper_style.INK,
               markersize=4, label=r"Mean $\pm$ 1 SD")])
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    fig.tight_layout(pad=1.15)
    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / "qclt_vs_covariance_methods.pdf", bbox_inches="tight")
    plt.close(fig)


def generate():
    errors = compare_methods(np.random.default_rng(20261115))
    save_covariance_errors(errors)
    plot()


if __name__ == "__main__":
    if "--plot-only" in sys.argv:
        plot()
    elif "--table-only" in sys.argv:
        errs, budget = load_covariance_errors()
        write_covariance_table(errs, budget)
    else:
        generate()
